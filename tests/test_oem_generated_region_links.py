"""Integration: OSM KD split -> two physically packed type-0/type-1 SDAL
spatial parcels -> genuine type-255 index, including negative corruption.

This checks the *generated bytes*, not fixtures containing only fake
PclHdr headers. The resulting region is NOT a full Denso navigation map.
"""
from __future__ import annotations

from dataclasses import replace
import io
from pathlib import Path
import sys
import unittest

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/"src"))

from test_oem_typed_headers import sample
from sdal_builder.oem_spatial_header import DBRect, make_spatial_header
from sdal_builder.oem_line_geometry import FullPolyline, CartographicPosition
from sdal_builder.oem_typed_records import RoutingNodeBasic
from sdal_builder.oem_route_segments import RoutingSegmentRegular
from sdal_builder.oem_parcel_assembly import (
    CartographicRoad, SizeAuthority, assemble_cartographic_roads,
    assemble_routing_regular, verify_bounded_parcel, ParcelAssemblyError,
)
from sdal_builder.oem_kd_codec import SpatialRef
from sdal_builder.osm_spatial_plan import (
    Footprint, Rect, plan_spatial_partition, leaf_inventory,
    compile_planned_index, SpatialPlanError,
)
from sdal_builder.oem_index import decode_index_parcel

SIZE = SizeAuthority(256,{24:4096})
BASE=Rect(0,5242880,524288,5767168)

def make_header(kind,pid,cell:Rect):
    sample_header=sample(kind,0)
    rect=DBRect(cell.west,cell.south,cell.east,cell.north)
    ancestor=DBRect(BASE.west,BASE.south,BASE.east,BASE.north)
    prefix=make_spatial_header(parcel_id=pid,parcel_type=kind,
                bounds=rect,tile=rect,ancestor=ancestor,scale=0,layer=0)
    return replace(sample_header,spatial_prefix=prefix)

def build_region():
    features=(
        Footprint(301,1,0,100000,5300000,100300,5300300),
        Footprint(401,0,0,400000,5300000,400300,5300300),
    )
    plan=plan_spatial_partition(BASE,features,max_features_per_leaf=1)
    leaves=leaf_inventory(plan)
    assert set(leaves)=={"L","R"}
    carto=assemble_cartographic_roads(make_header(1,0x18000020,leaves["L"].rect),
        (CartographicRoad(
             FullPolyline(0,0,5300000,100000,True,3,1,1,
                          rank=1,attribute_index=5),
             (CartographicPosition(5300200,100300),)),),
        authority=SIZE,file_offset=0x2000)
    nodes=(RoutingNodeBasic(5300000,400000,(0,),b""),
           RoutingNodeBasic(5300200,400300,(0,),b""))
    segments=(RoutingSegmentRegular(0,1,3,10,220,1,0,False,
                                    False,1,25,300,5),)
    routing=assemble_routing_regular(
        make_header(0,0x18000040,leaves["R"].rect),nodes,segments,
        minimum_node_id=1234,minimum_segment_id=4321,
        authority=SIZE,file_offset=0x4000)
    region=bytearray(0xC200+0x5000)
    region[0x2000:0x3000]=carto.blob
    region[0x4000:0x5000]=routing.blob
    refs={"L":(SpatialRef(1,0,0x18000020),),
          "R":(SpatialRef(0,0,0x18000040),)}
    index=compile_planned_index(plan,parcel_refs=refs,
                  entity_id_bounds={"":(1234,4321)},
                  file_offset=0xC200,target_file=io.BytesIO(region))
    region[0xC200:0xC200+len(index)]=index
    return bytes(region),plan,index,carto,routing,refs

class GeneratedRegionLinkTests(unittest.TestCase):
    def test_two_real_payloads_linked_by_oem_type255_global_kd(self):
        contents,plan,index,carto,routing,refs=build_region()
        self.assertEqual(contents[0x2000:0x3000],carto.blob)
        self.assertEqual(contents[0x4000:0x5000],routing.blob)
        self.assertEqual(index,contents[0xC200:0xC200+0x5000])
        self.assertEqual(decode_index_parcel(index,
                            absolute_offset=0xC200).reassemble(),index)
        self.assertEqual(verify_bounded_parcel(
             contents[0x2000:0x3000],authority=SIZE,
             file_offset=0x2000)["record_counts"],{"lineDesc":1})
        self.assertEqual(verify_bounded_parcel(
             contents[0x4000:0x5000],authority=SIZE,
             file_offset=0x4000)["record_counts"],{"nodeDesc":2,"segmentDesc":1})
        self.assertEqual(set(leaf_inventory(plan)),{"L","R"})

    def test_corrupt_real_target_pid_rejected_during_kd_generation(self):
        contents,plan,_,_,_,refs=build_region()
        data=bytearray(contents)
        data[0x4000]^=1
        with self.assertRaisesRegex(SpatialPlanError,"target_pid_mismatch"):
            compile_planned_index(plan,parcel_refs=refs,
                entity_id_bounds={"":(1234,4321)},target_file=io.BytesIO(data))

    def test_internal_corruption_detected_after_header_still_matches(self):
        contents,_,_,_,_,_=build_region()
        data=bytearray(contents)
        # Cartographic lineDesc 16-bit physical block-offset table.
        from sdal_builder.oem_typed_headers import decode_typed_fixed_header
        head=decode_typed_fixed_header(data[0x2000:0x3000])
        table=dict(head.descriptors)["lineDesc"][0]
        data[0x2000+table]^=1
        # PclHdr still matches; internal per-record block is now broken.
        with self.assertRaises((ParcelAssemblyError,ValueError)):
            verify_bounded_parcel(data[0x2000:0x3000],
                                  authority=SIZE,file_offset=0x2000)

    def test_entire_generated_region_deterministic(self):
        a=build_region()
        b=build_region()
        self.assertEqual(a,b)

if __name__=="__main__":
    unittest.main()
